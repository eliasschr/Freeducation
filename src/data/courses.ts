export const providerSummaries = Array.from(new Set(courses.map((course) => course.provider))).map((provider) => {
  const providerCourses = courses.filter((course) => course.provider === provider);
  const topics = Array.from(new Set(providerCourses.flatMap((course) => course.topics).slice(0, 8)));
  return {
    name: provider,
    courseCount: providerCourses.length,
    topics,
    categories: Array.from(new Set(providerCourses.map((course) => course.category))),
  };
});
